#!/usr/bin/env python3
"""Turn the ASCII Rickroll frames into a C header for 3dfetch.

Reads the frames out of the upstream ASCII_Rickroll.h and writes a header
with the portrait, cropped to the columns the logo canvas has.

    python3 tools/make-rickroll.py
"""

import re
import sys
from pathlib import Path

UPSTREAM = "https://raw.githubusercontent.com/johnsoupir/ASCII_Rickroll/main/C%20Rickroll/ASCII_Rickroll.h"
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rickroll.h"

W, H = 96, 36
COLS = 60
STEP = 4


def frames_from(text):
    body = text[text.index("static const char frames[] = {"):]
    nums = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]
    out = []
    for f in range(0, len(nums) // (W * H), STEP):
        off = f * W * H
        raw = bytes(nums[off:off + W * H])
        rows = []
        for l in range(H):
            row = raw[l * W:l * W + COLS].decode("latin-1")
            rows.append("".join(" " if ord(c) < 32 else c for c in row))
        out.append(rows)
    return out


def main():
    import urllib.request
    text = urllib.request.urlopen(UPSTREAM).read().decode("utf-8", "replace")
    frames = frames_from(text)
    if not frames:
        raise SystemExit("no frames found")

    with open(OUT, "w") as f:
        f.write("// The Rickroll art for --nggyu.\n")
        f.write("//\n")
        f.write("// An ASCII portrait of Rick Astley, cropped to the columns the\n")
        f.write("// logo canvas has. Every fourth frame of the original animation\n")
        f.write("// is kept, which is about eight frames a second when played back.\n")
        f.write("//\n")
        f.write("// Art from https://github.com/johnsoupir/ASCII_Rickroll\n")
        f.write("//\n")
        f.write("// Generated by tools/make-rickroll.py - don't edit by hand.\n")
        f.write("\n")
        f.write("#ifndef RICKROLL_H\n#define RICKROLL_H\n\n")
        f.write("#define RICK_FRAME_ROWS %d\n" % H)
        f.write("#define RICK_FRAME_COLS %d\n" % COLS)
        f.write("#define RICK_FRAME_COUNT %d\n\n" % len(frames))
        f.write("static const char *const rick_frames[RICK_FRAME_COUNT][RICK_FRAME_ROWS] = {\n")
        for rows in frames:
            f.write("  {\n")
            for row in rows:
                f.write('    "%s",\n' % row.replace("\\", "\\\\").replace('"', '\\"'))
            f.write("  },\n")
        f.write("};\n\n#endif\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(frames)} frames)")


if __name__ == "__main__":
    main()
